/**
 * Generates clean .env.example files from existing .env files with all secrets stripped.
 */

import { parseDotenv } from './parser.js';
import { isLikelySecret } from './masker.js';
import { validateType } from './types.js';

/**
 * Infers an appropriate schema type from an existing value.
 * @param {string} key
 * @param {string} value
 * @returns {string}
 */
export function inferType(key, value) {
  if (!value) return 'string';

  const trimmed = value.trim();

  // Check port
  if (/port/i.test(key) && /^\d+$/.test(trimmed)) {
    const num = Number(trimmed);
    if (num >= 1 && num <= 65535) {
      return 'port';
    }
  }

  // Check bool
  if (/^(true|false)$/i.test(trimmed)) {
    return 'bool';
  }

  // Check int
  if (/^-?\d+$/.test(trimmed)) {
    return 'int';
  }

  // Check email
  if (validateType(trimmed, 'email').valid) {
    return 'email';
  }

  // Check url
  if (validateType(trimmed, 'url').valid) {
    return 'url';
  }

  return 'string';
}

/**
 * Generates .env.example file content from an existing .env content string.
 *
 * @param {string} envContent - Content of source .env
 * @param {object} [options]
 * @param {boolean} [options.keepSafeDefaults=true] - Keep common non-sensitive defaults (e.g. PORT=3000, NODE_ENV=development)
 * @returns {string}
 */
export function generateExample(envContent, options = {}) {
  const { keepSafeDefaults = true } = options;
  const { entries } = parseDotenv(envContent);

  const outputLines = [];
  outputLines.push('# Environment variables schema and defaults');
  outputLines.push('# Generated by env-check (https://github.com/YusufBeratZengin/env-check)');
  outputLines.push('');

  for (const entry of entries) {
    const { key, value, comments } = entry;
    const isSecret = isLikelySecret(key);

    const hasType = comments.some(c => /#\s*@type\b/i.test(c));
    const hasRequired = comments.some(c => /#\s*@required\b/i.test(c));
    const hasSecret = comments.some(c => /#\s*@secret\b/i.test(c));

    // Preserve non-annotation comments
    for (const comment of comments) {
      if (!/#\s*@(type|required|secret|default|pattern)\b/i.test(comment)) {
        outputLines.push(comment);
      }
    }

    // Add @type if not present
    if (!hasType) {
      const type = inferType(key, value);
      outputLines.push(`# @type ${type}`);
    } else {
      const existing = comments.find(c => /#\s*@type\b/i.test(c));
      outputLines.push(existing);
    }

    // Add @secret if detected
    if (isSecret && !hasSecret) {
      outputLines.push('# @secret');
    } else if (hasSecret) {
      outputLines.push('# @secret');
    }

    // Add @required
    if (!hasRequired) {
      outputLines.push('# @required');
    } else {
      outputLines.push('# @required');
    }

    // Value stripping:
    // If it's a secret, value is strictly empty
    // If keepSafeDefaults is true and it's a known benign non-secret value (like port, env name), keep it
    let exampleVal = '';
    if (!isSecret && keepSafeDefaults) {
      if (key === 'NODE_ENV') {
        exampleVal = value || 'development';
      } else if (/port/i.test(key) && /^\d+$/.test(value)) {
        exampleVal = value;
      } else if (key === 'HOST') {
        exampleVal = value || 'localhost';
      }
    }

    outputLines.push(`${key}=${exampleVal}`);
    outputLines.push('');
  }

  return outputLines.join('\n').trimEnd() + '\n';
}
